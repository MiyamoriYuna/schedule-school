// ========================================
// 学年から学校種別を判断
// ========================================

function getSchoolLevel(grade) {

  if (grade.startsWith("中学")) {

    return "juniorHigh";

  }


  if (grade.startsWith("高校")) {

    return "highSchool";

  }


  return null;

}


// ========================================
// 学年に応じた教科データを取得
// ========================================

function getSubjectsForGrade(grade) {

  const schoolLevel =
    getSchoolLevel(grade);


  if (schoolLevel === "juniorHigh") {

    return juniorHighSubjects;

  }


  if (schoolLevel === "highSchool") {

    return highSchoolSubjects;

  }


  return {};

}
